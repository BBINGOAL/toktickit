import { test, expect, prisma, signIn, openTicket, createWork } from './fixtures'

test('two staff create, assign, edit, start, complete, follow up and cancel; Requester reads shared history', async ({ page, work }) => {
  await signIn(page, work.staff); await openTicket(page, work.ticket.id)
  await createWork(page, 'Inspect VPN from UI')
  const first = await prisma.actionTaken.findFirstOrThrow({ where: { ticketId: work.ticket.id } })
  await page.getByRole('button', { name: `Edit action #${first.id}`, exact: true }).click()
  await page.getByLabel('Find active assignee by name').fill(work.colleague.name)
  await expect(page.getByLabel('Assignee', { exact: true }).getByRole('option', { name: `${work.colleague.name} (IT_STAFF)`, exact: true })).toHaveCount(1)
  await page.getByLabel('Assignee', { exact: true }).selectOption(String(work.colleague.id))
  await page.getByLabel('Action description', { exact: true }).fill('Inspect VPN configuration')
  await page.getByRole('button', { name: 'Start action', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: `Edit action #${first.id}`, exact: true }).click()
  await page.getByLabel('Result', { exact: true }).fill('VPN configuration repaired')
  await page.getByRole('checkbox', { name: 'Follow-up required?' }).check()
  await page.getByLabel('Follow-up note (required)', { exact: true }).fill('Verify on campus network')
  await page.getByRole('button', { name: 'Complete action', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('button', { name: `Edit action #${first.id}`, exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: `Add follow-up to #${first.id}`, exact: true }).click()
  await page.getByLabel('Action description', { exact: true }).fill('Verify network follow-up')
  await page.getByRole('button', { name: 'Create action', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.context().clearCookies(); await signIn(page, work.colleague); await openTicket(page, work.ticket.id)
  await createWork(page, 'Second staff duplicate diagnostic')
  const last = await prisma.actionTaken.findFirstOrThrow({ where: { ticketId: work.ticket.id, performedById: work.colleague.id } })
  await page.getByRole('button', { name: `Edit action #${last.id}`, exact: true }).click()
  await page.getByLabel('Cancellation reason (required to cancel)').fill('Covered by first diagnostic')
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Cancel action', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect((await prisma.ticket.findUniqueOrThrow({ where: { id: work.ticket.id } })).ownerId).toBe(work.staff.id)
  const actions = await prisma.actionTaken.findMany({ where: { ticketId: work.ticket.id }, orderBy: { id: 'asc' } })
  expect(actions).toHaveLength(3)
  expect(actions[0]).toMatchObject({ status: 'COMPLETED', performedById: work.staff.id, assigneeId: work.colleague.id })
  expect(actions[1].followsUpActionId).toBe(first.id)
  expect(actions[2].status).toBe('CANCELLED')
  await page.context().clearCookies(); await signIn(page, work.requester); await openTicket(page, work.ticket.id)
  await expect(page.getByRole('button', { name: 'New action', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: /^Edit action/ })).toHaveCount(0)
  await expect(page.getByText('Inspect VPN configuration', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: `Details and history #${first.id}`, exact: true }).click()
  await expect(page.getByRole('heading', { name: 'History (read-only)' })).toBeVisible()
  await expect(page.getByRole('dialog').getByText('COMPLETED', { exact: true }).first()).toBeVisible()
  expect(await prisma.actionTakenEvent.count({ where: { actionId: first.id } })).toBe(3)
})
