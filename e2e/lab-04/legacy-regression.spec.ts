  await dialog.getByLabel('Full Name').fill('Edited regression requester')
  await dialog.getByRole('button', { name: 'Save User', exact: true }).click()
  await expect(dialog).toHaveCount(0); await expect(row).toContainText('Edited regression requester')
  await row.getByRole('button', { name: 'Edit', exact: true }).click()
  await dialog.getByLabel('Set New Password (Optional)').fill('resetPassword123')
  await dialog.getByRole('button', { name: 'Reset', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('Password reset successfully')
  await dialog.getByRole('button', { name: 'Close', exact: true }).click()
