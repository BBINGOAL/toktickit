import { test,expect,prisma,signIn,openTicket,createWork } from './fixtures'

test('resolution gate, advisory, current-cycle work, close/reopen and public history survive the full lifecycle',async({page,work})=>{
  await signIn(page,work.staff);await openTicket(page,work.ticket.id)
  const workflow=page.getByRole('region',{name:'Ticket workflow',exact:true})
  await page.getByLabel('Update Status',{exact:true}).selectOption('IN_PROGRESS')
  await workflow.getByRole('button',{name:'Apply status',exact:true}).click()
  await expect(workflow).toContainText('Version 1')
  await page.getByLabel('Update Status',{exact:true}).selectOption('RESOLVED')
  await page.getByLabel('Resolution summary (required)',{exact:true}).fill('VPN verified')
  await workflow.getByRole('button',{name:'Apply status',exact:true}).click()
  await expect(workflow.getByRole('alert')).toContainText('workflow requirements')
  await page.getByRole('button',{name:'Reload Ticket (keep drafts)',exact:true}).click()
  await expect(page.getByLabel('Update Status',{exact:true})).toBeEnabled()
  await createWork(page,'Inspect and fix VPN')
  const action=await prisma.actionTaken.findFirstOrThrow({where:{ticketId:work.ticket.id}})
  await page.getByRole('button',{name:`Edit action #${action.id}`,exact:true}).click()
  await page.getByRole('button',{name:'Start action',exact:true}).click();await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button',{name:`Edit action #${action.id}`,exact:true}).click()
  await page.getByLabel('Result',{exact:true}).fill('Connectivity verified')
  await page.getByRole('button',{name:'Complete action',exact:true}).click();await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(workflow).toContainText('Version 4')
  await page.context().clearCookies();await signIn(page,work.requester);await openTicket(page,work.ticket.id)
  await workflow.getByRole('button',{name:'Problem appears resolved',exact:true}).click()
  await expect(workflow).toContainText('You indicated that this problem appears resolved.')
  expect((await prisma.ticket.findUniqueOrThrow({where:{id:work.ticket.id}})).status).toBe('IN_PROGRESS')
  await page.context().clearCookies();await signIn(page,work.staff);await openTicket(page,work.ticket.id)
  await page.getByLabel('Update Status',{exact:true}).selectOption('RESOLVED')
  await page.getByLabel('Resolution summary (required)',{exact:true}).fill('VPN configuration repaired and verified')
  await workflow.getByRole('button',{name:'Apply status',exact:true}).click();await expect(workflow).toContainText('Version 6')
  await page.getByLabel('Update Status',{exact:true}).selectOption('CLOSED')
  await workflow.getByRole('button',{name:'Apply status',exact:true}).click();await expect(workflow).toContainText('Version 7')
  await page.getByLabel('Update Status',{exact:true}).selectOption('REOPENED')
  await workflow.getByRole('button',{name:'Apply status',exact:true}).click();await expect(workflow).toContainText('Work cycle 2')
  const reopened=await prisma.ticket.findUniqueOrThrow({where:{id:work.ticket.id}})
  expect(reopened.requesterResolved).toBe(false);expect(reopened.resolvedAt).toBeNull()
  await page.getByLabel('Update Status',{exact:true}).selectOption('IN_PROGRESS')
  await workflow.getByRole('button',{name:'Apply status',exact:true}).click();await expect(workflow).toContainText('Version 9')
  await page.getByLabel('Update Status',{exact:true}).selectOption('RESOLVED')
  await page.getByLabel('Resolution summary (required)',{exact:true}).fill('Old cycle must not qualify')
  await workflow.getByRole('button',{name:'Apply status',exact:true}).click();await expect(workflow.getByRole('alert')).toBeVisible()
  await expect(page.getByRole('heading',{name:'Ticket history',exact:true})).toBeVisible()
})

test('Ticket cancellation cancels pending actions while keeping completed work and audit',async({page,work})=>{
  await signIn(page,work.staff);await openTicket(page,work.ticket.id);await createWork(page,'Work no longer needed')
  await page.getByLabel('Update Status',{exact:true}).selectOption('CANCELLED')
  await page.getByLabel('Ticket cancellation reason (required)',{exact:true}).fill('Duplicate request')
  page.once('dialog',d=>d.accept())
  await page.getByRole('button',{name:'Apply status',exact:true}).click()
  const workflow=page.getByRole('region',{name:'Ticket workflow',exact:true})
  await expect(workflow).toContainText('Version 2')
  await expect(page.getByRole('button',{name:'New action',exact:true})).toHaveCount(0)
  const action=await prisma.actionTaken.findFirstOrThrow({where:{ticketId:work.ticket.id}})
  expect(action.status).toBe('CANCELLED');expect(action.cancellationReason).toBe('Duplicate request')
  expect(await prisma.actionTakenEvent.count({where:{actionId:action.id}})).toBe(2)
})

test('stale workflow keeps summary and lost response replays a single event',async({page,work})=>{
  await signIn(page,work.staff);await openTicket(page,work.ticket.id)
  await page.getByLabel('Update Status',{exact:true}).selectOption('IN_PROGRESS')
  await prisma.ticket.update({where:{id:work.ticket.id},data:{version:{increment:1}}})
  await page.getByRole('button',{name:'Apply status',exact:true}).click()
  await expect(page.getByRole('region',{name:'Ticket workflow',exact:true}).getByRole('alert')).toBeVisible()
  await page.getByRole('button',{name:'Reload Ticket (keep drafts)',exact:true}).click()
  await expect(page.getByLabel('Update Status',{exact:true})).toBeEnabled()
  let lost=false
  await page.route(`**/api/tickets/${work.ticket.id}/status`,async route=>{
    if(!lost){lost=true;await route.fetch();return route.abort('failed')}return route.continue()
  })
  await page.getByRole('button',{name:'Apply status',exact:true}).click()
  await expect(page.getByRole('button',{name:'Retry same workflow submission',exact:true})).toBeEnabled()
  await page.getByRole('button',{name:'Retry same workflow submission',exact:true}).click()
  await expect(page.getByRole('region',{name:'Ticket workflow',exact:true})).toContainText('Version 2')
  expect(await prisma.ticketWorkflowEvent.count({where:{ticketId:work.ticket.id}})).toBe(1)
})

test('a completed action requiring follow-up blocks Resolve until its linked successor is completed',async({page,work})=>{
  await signIn(page,work.staff);await openTicket(page,work.ticket.id)
  const workflow=page.getByRole('region',{name:'Ticket workflow',exact:true})
  await page.getByLabel('Update Status',{exact:true}).selectOption('IN_PROGRESS')
  await workflow.getByRole('button',{name:'Apply status',exact:true}).click();await expect(workflow).toContainText('Version 1')
  await createWork(page,'Initial network repair')
  const first=await prisma.actionTaken.findFirstOrThrow({where:{ticketId:work.ticket.id}})
  await page.getByRole('button',{name:`Edit action #${first.id}`,exact:true}).click()
  await page.getByRole('button',{name:'Start action',exact:true}).click();await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button',{name:`Edit action #${first.id}`,exact:true}).click()
  await page.getByLabel('Result',{exact:true}).fill('Repair done; verify on campus')
  await page.getByRole('checkbox',{name:'Follow-up required?'}).check()
  await page.getByLabel('Follow-up note (required)',{exact:true}).fill('Verify connectivity')
  await page.getByRole('button',{name:'Complete action',exact:true}).click();await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(workflow).toContainText('Version 4')
  await page.getByLabel('Update Status',{exact:true}).selectOption('RESOLVED')
  await page.getByLabel('Resolution summary (required)',{exact:true}).fill('Work verified')
  await workflow.getByRole('button',{name:'Apply status',exact:true}).click();await expect(workflow.getByRole('alert')).toContainText('follow-up')
  await page.getByRole('button',{name:'Reload Ticket (keep drafts)',exact:true}).click()
  await expect(page.getByLabel('Update Status',{exact:true})).toBeEnabled()
  await page.getByRole('button',{name:`Add follow-up to #${first.id}`,exact:true}).click()
  await page.getByLabel('Action description',{exact:true}).fill('Campus connectivity verification')
  await page.getByRole('button',{name:'Create action',exact:true}).click();await expect(page.getByRole('dialog')).toHaveCount(0)
  const next=await prisma.actionTaken.findFirstOrThrow({where:{ticketId:work.ticket.id,followsUpActionId:first.id}})
  await page.getByRole('button',{name:`Edit action #${next.id}`,exact:true}).click()
  await page.getByRole('button',{name:'Start action',exact:true}).click();await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button',{name:`Edit action #${next.id}`,exact:true}).click()
  await page.getByLabel('Result',{exact:true}).fill('Campus connectivity verified')
  await page.getByRole('button',{name:'Complete action',exact:true}).click();await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(workflow).toContainText('Version 7')
  await workflow.getByRole('button',{name:'Apply status',exact:true}).click();await expect(workflow).toContainText('Version 8')
  expect((await prisma.ticket.findUniqueOrThrow({where:{id:work.ticket.id}})).status).toBe('RESOLVED')
})
